package dev.shadowgarden.app.books

import dev.shadowgarden.app.progress.CatalogBookId
import dev.shadowgarden.app.progress.EditionFingerprint
import java.io.IOException
import java.io.InputStream
import java.nio.file.Files
import java.util.concurrent.CancellationException
import org.junit.Assert.assertArrayEquals
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder

class PrivateBookStoreTest {
    @get:Rule val files = TemporaryFolder()
    private val id = CatalogBookId("bk_abcdefghijklmnopqrstuv")
    private val other = CatalogBookId("bk_0123456789abcdefghijkl")
    private val old = "original generated bytes".toByteArray()
    private val fresh = "replacement generated bytes".toByteArray()
    private fun fingerprint(bytes: ByteArray) = EditionFingerprint.calculate(bytes.inputStream(), 1_000)

    @Test fun savesAndReopensExactEditionInIndependentStore() {
        val directory = files.newFolder()
        assertEquals(fingerprint(old), PrivateBookStore(directory).replace(id, old.inputStream(), fingerprint(old)))
        PrivateBookStore(directory).open(id)!!.use { opened ->
            assertEquals(fingerprint(old), opened.edition)
            assertArrayEquals(old, opened.input.readBytes())
        }
        assertNull(PrivateBookStore(directory).open(other))
        assertEquals(listOf(id.value + ".epub"), directory.list()!!.toList())
    }

    @Test fun failuresPreserveExistingEditionAndRemovePartialFile() {
        val directory = files.newFolder()
        val store = PrivateBookStore(directory, maxBytes = 64)
        store.replace(id, old.inputStream())
        val broken = object : InputStream() {
            var read = false
            override fun read(): Int { if (read) throw IOException("interrupted") else { read = true; return 42 } }
        }
        assertTrue(runCatching { store.replace(id, broken) }.isFailure)
        assertTrue(runCatching { store.replace(id, ByteArray(65).inputStream()) }.isFailure)
        assertTrue(runCatching { store.replace(id, byteArrayOf().inputStream()) }.isFailure)
        assertTrue(runCatching { store.replace(id, fresh.inputStream(), fingerprint(old)) }.isFailure)
        assertTrue(runCatching { store.replace(id, fresh.inputStream()) { throw CancellationException("cancelled") } }.isFailure)
        store.open(id)!!.use { assertArrayEquals(old, it.input.readBytes()) }
        assertFalse(directory.resolve(id.value + ".part").exists())
    }

    @Test fun lateCancellationDoesNotReplaceThePreviousEdition() {
        val store = PrivateBookStore(files.newFolder())
        store.replace(id, old.inputStream())
        var checks = 0
        assertTrue(runCatching {
            store.replace(id, fresh.inputStream()) { if (++checks == 4) throw CancellationException() }
        }.isFailure)
        store.open(id)!!.use { assertArrayEquals(old, it.input.readBytes()) }
    }

    @Test fun anOpenDescriptorRetainsItsEditionAfterReplacementAndRemoval() {
        val store = PrivateBookStore(files.newFolder())
        store.replace(id, old.inputStream())
        store.open(id)!!.use { opened ->
            store.replace(id, fresh.inputStream())
            assertEquals(fingerprint(old), opened.edition)
            assertArrayEquals(old, opened.input.readBytes())
            store.open(id)!!.use { assertEquals(fingerprint(fresh), it.edition) }
            assertTrue(store.remove(id))
            assertFalse(store.remove(id))
            assertNull(store.open(id))
        }
    }

    @Test fun interruptedTemporaryFileIsDiscardedWithoutChangingExistingBook() {
        val directory = files.newFolder()
        val store = PrivateBookStore(directory)
        store.replace(id, old.inputStream())
        directory.resolve(id.value + ".part").writeText("partial")
        assertTrue(runCatching { store.replace(id, fresh.inputStream(), fingerprint(old)) }.isFailure)
        store.open(id)!!.use { assertArrayEquals(old, it.input.readBytes()) }
        assertFalse(directory.resolve(id.value + ".part").exists())
    }

    @Test fun confirmedRemovalDoesNotDeleteAChangedEdition() {
        val store = PrivateBookStore(files.newFolder())
        val original = store.replace(id, old.inputStream())
        val replacement = store.replace(id, fresh.inputStream())
        assertEquals(BookRemovalResult.EDITION_CHANGED, store.removeIfEdition(id, original))
        store.open(id)!!.use { assertArrayEquals(fresh, it.input.readBytes()) }
        assertEquals(BookRemovalResult.REMOVED, store.removeIfEdition(id, replacement))
        assertEquals(BookRemovalResult.NOT_FOUND, store.removeIfEdition(id, replacement))
    }

    @Test fun savedShelfListsOnlyValidOwnedFilesAndReportsUnavailableOnes() {
        val directory = files.newFolder()
        val store = PrivateBookStore(directory, maxBytes = 64)
        store.replace(id, old.inputStream())
        store.replace(other, fresh.inputStream())
        directory.resolve("not-a-book.epub").writeText("ignored")
        directory.resolve(id.value + ".part").writeText("partial")
        val emptyId = CatalogBookId("bk_zzzzzzzzzzzzzzzzzzzzzz")
        directory.resolve(emptyId.value + ".epub").writeBytes(byteArrayOf())
        val linkId = CatalogBookId("bk_yyyyyyyyyyyyyyyyyyyyyy")
        Files.createSymbolicLink(directory.resolve(linkId.value + ".epub").toPath(), directory.resolve(id.value + ".epub").toPath())
        val list = store.listSaved()
        assertEquals(listOf(SavedBook(other, fresh.size.toLong()), SavedBook(id, old.size.toLong())), list.books)
        assertEquals(2, list.unavailableCount)
        assertTrue(directory.resolve(emptyId.value + ".epub").exists())
        assertTrue(Files.isSymbolicLink(directory.resolve(linkId.value + ".epub").toPath()))
    }

    @Test fun savedShelfDistinguishesMissingDirectoryFromBrokenStorage() {
        val parent = files.newFolder()
        val directory = parent.resolve("books")
        assertEquals(SavedBooks(emptyList(), 0), PrivateBookStore(directory).listSaved())
        directory.writeText("not a directory")
        assertTrue(runCatching { PrivateBookStore(directory).listSaved() }.exceptionOrNull() is IOException)
    }
}
